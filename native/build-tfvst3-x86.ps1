# Builds Source\native\tfvst3 for Win32 (x86 Release, static CRT) and copies tfvst3-x86.dll beside the helpers.
# The 32-bit helper loads it for Windows VST3 under Wine (and for a future Windows 32-bit VST3 route).
# Records Source\native\BUILD_PROVENANCE_X86.md with the SDK pin, compiler and SHA-256; Package-Release.ps1 verifies it.
# Usage: .\build-tfvst3-x86.ps1 [-Clean] [-NoTest] [-BuildDir <path>]
[CmdletBinding()]
param([switch]$Clean, [switch]$NoTest, [string]$BuildDir = '')
$ErrorActionPreference = 'Stop'

$candidate = Split-Path -Parent $PSScriptRoot
if (Test-Path (Join-Path $candidate 'TabForge.sln')) { $sourceRoot = $candidate; $repoRoot = Split-Path -Parent $candidate }
else { $repoRoot = $candidate; $sourceRoot = $candidate }
$src = Join-Path $PSScriptRoot 'tfvst3'
$buildDir = if ($BuildDir) { $BuildDir } else { Join-Path $src 'build32' }
$sdk = Join-Path $sourceRoot 'third_party\vst3sdk'
$destDir = Join-Path $sourceRoot 'src\TabForge.AudioEngine\native'
$provenance = Join-Path $PSScriptRoot 'BUILD_PROVENANCE_X86.md'

$cmake = 'C:\Program Files\CMake\bin\cmake.exe'
if (-not (Test-Path $cmake)) { $cmake = 'cmake' }
$git = 'C:\Program Files\Git\cmd\git.exe'
if (-not (Test-Path $git)) { $git = 'git' }

& (Join-Path $PSScriptRoot 'fetch-vst3sdk.ps1')
if ($Clean -and (Test-Path $buildDir)) { Remove-Item -Recurse -Force $buildDir }

$testFlag = if ($NoTest) { 'OFF' } else { 'ON' }
$configured = Test-Path (Join-Path $buildDir 'CMakeCache.txt')
$generator = $null
if (-not $configured) {
    foreach ($gen in @('Visual Studio 18 2026', 'Visual Studio 17 2022')) {
        Write-Host "Configuring with '$gen' (Win32)..."
        & $cmake -S $src -B $buildDir -G $gen -A Win32 "-DTFVST3_BUILD_TEST=$testFlag" "-DVST3SDK_DIR=$sdk"
        if ($LASTEXITCODE -eq 0) { $configured = $true; $generator = $gen; break }
        if (Test-Path $buildDir) { Remove-Item -Recurse -Force $buildDir }
    }
    if (-not $configured) { throw 'CMake configure failed for all Visual Studio generators (Win32)' }
}

& $cmake --build $buildDir --config Release --parallel
if ($LASTEXITCODE -ne 0) { throw "tfvst3 x86 build failed ($LASTEXITCODE)" }

$dll = Join-Path $buildDir 'Release\tfvst3.dll'
if (-not (Test-Path $dll)) { throw "build succeeded but $dll is missing" }
New-Item -ItemType Directory -Force $destDir | Out-Null
$target = Join-Path $destDir 'tfvst3-x86.dll'
Copy-Item $dll $target -Force
Write-Host "tfvst3-x86.dll -> $destDir"

if (Test-Path (Join-Path $sdk '.git')) {
    $sdkCommit = (& $git -C $sdk rev-parse HEAD).Trim()
    $sdkDescribe = (& $git -C $sdk describe --tags --always 2>$null | Out-String).Trim()
} else {
    $pin = Select-String -Path (Join-Path $PSScriptRoot 'fetch-vst3sdk.ps1') -Pattern "^\`$Sdk(Commit|Tag)\s*=\s*'([^']+)'" | ForEach-Object { $_.Matches[0] }
    $sdkCommit = ($pin | Where-Object { $_.Groups[1].Value -eq 'Commit' }).Groups[2].Value
    $sdkDescribe = ($pin | Where-Object { $_.Groups[1].Value -eq 'Tag' }).Groups[2].Value + ' (trimmed copy)'
}
$compilerVersion = 'unknown'
$compilerId = 'unknown'
$cxxInfo = Get-ChildItem -Path (Join-Path $buildDir 'CMakeFiles') -Filter 'CMakeCXXCompiler.cmake' -Recurse -ErrorAction SilentlyContinue | Select-Object -First 1
if ($cxxInfo) {
    $text = [IO.File]::ReadAllText($cxxInfo.FullName)
    if ($text -match 'set\(CMAKE_CXX_COMPILER_VERSION "([^"]+)"\)') { $compilerVersion = $Matches[1] }
    if ($text -match 'set\(CMAKE_CXX_COMPILER_ID "([^"]+)"\)') { $compilerId = $Matches[1] }
}
if (-not $generator -and (Test-Path (Join-Path $buildDir 'CMakeCache.txt'))) {
    $cache = [IO.File]::ReadAllText((Join-Path $buildDir 'CMakeCache.txt'))
    if ($cache -match 'CMAKE_GENERATOR:INTERNAL=(.+)') { $generator = $Matches[1].Trim() }
}
$cmakeVersion = ((& $cmake --version | Select-Object -First 1) -replace 'cmake version ', '').Trim()
$dllHash = (Get-FileHash -Algorithm SHA256 -LiteralPath $target).Hash.ToLowerInvariant()
$sources = @('tfvst3.cpp', 'tfvst3.h', 'tfv3_connection.h', 'tfv3_params.inc', 'CMakeLists.txt') | ForEach-Object {
    $p = Join-Path $src $_
    "- $_ SHA-256: $((Get-FileHash -Algorithm SHA256 -LiteralPath $p).Hash.ToLowerInvariant())"
}

$lines = @(
    '# tfvst3-x86 build provenance',
    '',
    'Generated by `Source/native/build-tfvst3-x86.ps1`; do not edit by hand. `Source/tools/Package-Release.ps1` verifies the',
    'shipped `tfvst3-x86.dll` against the hash recorded here, and `Source/tools/Write-Sbom.ps1` copies it into `Source/docs/reference/SBOM.md`.',
    '',
    "- Built (UTC): $([DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ss'))",
    "- VST3 SDK commit: $sdkCommit",
    "- VST3 SDK git describe: $sdkDescribe",
    "- Compiler: $compilerId $compilerVersion",
    "- CMake: $cmakeVersion; generator: $generator; platform Win32 (x86), configuration Release, static CRT",
    "- Tests built: $testFlag",
    '',
    '## Bridge source inputs',
    ''
) + $sources + @(
    '',
    '## Output',
    '',
    "tfvst3-x86.dll SHA-256: $dllHash"
)
[IO.File]::WriteAllText($provenance, (($lines -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Host "Provenance -> $provenance (tfvst3-x86.dll SHA-256 $dllHash)"
