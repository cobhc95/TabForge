    private static void TestVideoFrameGolden()
    {
        var bytes = FuzzFindSample("TabForge Demo - Ashen Meridian.gp5") ?? FuzzFindSample("TabForge Demo - Ashen Meridian.gp");
        if (bytes is null) { Check("video frame golden: the demo song is present", false); return; }
        var project = GuitarProImporter.ImportBytes(bytes, "demo.gp5");
        var timeline = RenderSpecBuilder.Compile(project);
        var (start, end) = RenderSpecBuilder.Bounds(timeline, RenderBounds.CustomBars, 0, 0, 1, -1, 0, 0);
        var hashes = new List<string>();
        foreach (var layout in new[] { VideoLayout.ScoreOnly, VideoLayout.Band, VideoLayout.Focus })
        {
            using var source = new VideoFrameSource(project, timeline, new AppSettings(), new VideoViewSpec
            {
                Layout = layout, Tracks = new[] { 0, 1 }, Dark = layout is VideoLayout.ScoreOnly or VideoLayout.Band, ShowInstrument = true, Width = 320, Height = 180,
            });
            for (var i = 0; i < VideoGoldenFrames; i++)
            {
                hashes.Add(Convert.ToHexString(SHA256.HashData(source.Render(start + (end - start) * i / VideoGoldenFrames))));
            }
        }
        var differing = Enumerable.Range(0, hashes.Count).Where(i => i >= VideoGoldenHashes.Length || VideoGoldenHashes[i] != hashes[i]).ToList();
        var detail = differing.Count == 0 ? null : $"{differing.Count} of {hashes.Count} differ, first at frame {differing[0]}; current: " + string.Join(",", hashes);
        Check($"video frame golden: {hashes.Count} frames match the recorded hashes", VideoGoldenHashes.Length == hashes.Count && differing.Count == 0, detail);
    }
